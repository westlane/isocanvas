/** Regenerate theme/schemes — run: yarn build:theme-schemes (excluded from `yarn test`). */

import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { describe, expect, it } from "vitest";
import { BUILT_IN_THEMES } from "@westlane/pino-blanc/themes";
import { themeToCssCustomProperties, isoCanvasThemeFromLogTheme } from "@westlane/isocanvas";

const themeRoot = join(import.meta.dirname, "..", "theme");
const schemesDir = join(themeRoot, "schemes");

/** `catppuccin-dark` → `dark/catppuccin` (one folder per appearance). */
function schemeRelPath(id: string): string {
  const match = /^(.+)-(dark|light)$/.exec(id);
  if (!match) {
    throw new Error(`Theme id must end in -dark or -light: ${id}`);
  }
  return `${match[2]}/${match[1]}.css`;
}

const schemeFileBanner = (id: string) => `/* ${id} — generated by yarn build:theme-schemes */\n\n`;

describe("generate theme schemes", () => {
  it("writes scheme css files and schemes.css barrel", () => {
    rmSync(schemesDir, { recursive: true, force: true });
    const schemeIds = Object.keys(BUILT_IN_THEMES).sort();

    for (const id of schemeIds) {
      const logTheme = BUILT_IN_THEMES[id];
      if (!logTheme) {
        throw new Error(`Missing built-in theme: ${id}`);
      }
      const iso = isoCanvasThemeFromLogTheme(logTheme);
      const props = themeToCssCustomProperties(iso);
      const body = Object.entries(props)
        .map(([name, value]) => `  ${name}: ${value};`)
        .join("\n");
      const css = `${schemeFileBanner(id)}
[data-ic-theme="${id}"] {
${body}
}
`;
      const file = join(schemesDir, schemeRelPath(id));
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, css, "utf8");
    }

    const barrel = schemeIds.map((id) => `@import "./schemes/${schemeRelPath(id)}";`).join("\n");
    writeFileSync(join(themeRoot, "schemes.css"), `${barrel}\n`);

    expect(schemeIds.length).toBeGreaterThan(0);
  });
});
